// Creating variables and performing basic arithmetic operations
let number1;
let number2;
let number3;

// Assigning values to the variables
number1 = 10;
number2 = 20;

// Performing addition
number3 = number1 + number2;

// Displaying the result in the console
let result = `The sum of ${number1} and ${number2} is ${number3}`;
// alert(message);
console.log(result);

// Performing subtraction
number3 = number1 - number2;
result = `The difference between ${number1} and ${number2} is ${number3}`;
console.log(result);

// Performing multiplication
number3 = number1 * number2;
result = `The product of ${number1} and ${number2} is ${number3}`;
console.log(result);

// Performing division
number3 = number1 / number2;
result = `${number1} divided by ${number2} gives ${number3}`;
console.log(result);

// Performing modulus operation
number3 = number1 % number2;
result = `The remainder of ${number1} divided by ${number2} is ${number3}`;
console.log(result);

// Performing exponentiation
number3 = number1 ** 2;
result = `${number1} raised to the power of 2 is ${number3}`;
console.log(result);